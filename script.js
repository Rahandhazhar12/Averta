const languagePicker = document.querySelector('#language');

function setLanguage(language) {
  const dictionary = translations[language] || translations.en;
  const isRtl = language === 'ckb' || language === 'ar';

  document.documentElement.lang = language;
  document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
  document.title = dictionary.pageTitle;

  if (languagePicker) {
    languagePicker.value = language;
    languagePicker.setAttribute('aria-label', dictionary.languageLabel);
  }

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const translation = dictionary[element.dataset.i18n];
    if (translation) {
      element.innerHTML = translation;
    }
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const translation = dictionary[element.dataset.i18nAriaLabel];
    if (translation) {
      element.setAttribute('aria-label', translation);
    }
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const translation = dictionary[element.dataset.i18nAlt];
    if (translation) {
      element.setAttribute('alt', translation);
    }
  });

  document.querySelectorAll('.buy-button').forEach((element) => {
    const productName = element.closest('.product-card').querySelector('h3')?.textContent || 'Gaming Mic GM-S88';
    element.setAttribute('aria-label', `${dictionary.buyNow}: ${productName}`);
  });

  try {
    localStorage.setItem('averta-language', language);
  } catch {
    // Storage is unavailable; the page still works without it.
  }
}

languagePicker?.addEventListener('change', (event) => setLanguage(event.target.value));

const productMainImage = document.querySelector('.product-main-image');
const galleryCounter = document.querySelector('.gallery-counter');
document.querySelectorAll('.product-thumbnails button').forEach((button, index) => {
  button.addEventListener('click', () => {
    const thumbnailImage = button.querySelector('img');
    if (productMainImage && thumbnailImage) {
      productMainImage.src = thumbnailImage.src;
      productMainImage.dataset.i18nAlt = button.dataset.imageAlt;
      const dictionary = translations[languagePicker?.value] || translations.en;
      productMainImage.alt = dictionary[button.dataset.imageAlt];
      document.querySelectorAll('.product-thumbnails button').forEach((thumbnail) => {
        const isActive = thumbnail === button;
        thumbnail.classList.toggle('is-active', isActive);
        thumbnail.setAttribute('aria-pressed', String(isActive));
      });
      if (galleryCounter) {
        galleryCounter.textContent = `0${index + 1} / 03`;
      }
    }
  });
});

try {
  const savedLanguage = localStorage.getItem('averta-language');
  if (savedLanguage && translations[savedLanguage]) {
    setLanguage(savedLanguage);
  } else {
    setLanguage('en');
  }
} catch {
  setLanguage('en');
}
